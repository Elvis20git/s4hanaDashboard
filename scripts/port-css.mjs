// One-off, reproducible CSS port: AIF/public/app.css -> src/styles/components.css (Tailwind @layer components).
//   node scripts/port-css.mjs <path to AIF/public/app.css>
// - drops the source's :root token blocks (they now live in the Tailwind @theme in src/styles/index.css)
// - renames every token reference to its Tailwind theme variable (--green -> --color-green, --shadow -> --shadow-card, ...)
// - wraps the rules in @layer components so utilities can still override them
import fs from 'node:fs';
const src = process.argv[2];
if (!src) { console.error('usage: node scripts/port-css.mjs <app.css>'); process.exit(1); }
let css = fs.readFileSync(src, 'utf8');

// remove :root{...} blocks that only define tokens (first big one + the later --amber one)
let removed = 0;
css = css.replace(/:root\{[^}]*\}/g, () => { removed++; return ''; });

const map = {
  'ink-2': 'color-ink-2', ink: 'color-ink',
  'hero-a': 'color-hero-a', 'hero-b': 'color-hero-b', 'hero-c': 'color-hero-c', 'hero-tx': 'color-hero-tx',
  canvas: 'color-canvas', card: 'color-card', 'line-2': 'color-line-2', line: 'color-line',
  'green-soft': 'color-green-soft', 'green-glow': 'color-green-glow', 'green-d': 'color-green-d', green: 'color-green', mint: 'color-mint',
  'gold-soft': 'color-gold-soft', 'gold-ink': 'color-gold-ink', 'gold-line': 'color-gold-line', gold: 'color-gold',
  'clay-soft': 'color-clay-soft', clay: 'color-clay',
  'tx-2': 'color-tx-2', 'tx-3': 'color-tx-3', tx: 'color-tx',
  'rail-tx-2': 'color-rail-tx-2', 'rail-tx-3': 'color-rail-tx-3', 'rail-tx-4': 'color-rail-tx-4', 'rail-tx': 'color-rail-tx',
  amber: 'color-amber',
  'font-display': 'font-display', 'font-body': 'font-body', 'font-mono': 'font-mono',
  'shadow-lg': 'shadow-lift', shadow: 'shadow-card',
};
const names = Object.keys(map).sort((a, b) => b.length - a.length).join('|');
const re = new RegExp('--(' + names + ')(?![\\w-])', 'g');
let renamed = 0;
css = css.replace(re, (_, n) => { renamed++; return '--' + map[n]; });

const header = `/* GENERATED by scripts/port-css.mjs from the source dashboard's app.css — do not hand-edit tokens here.
   Tokens live in src/styles/index.css (@theme). Everything below is the source's component CSS, unchanged except for
   token names (${renamed} references renamed, ${removed} :root token blocks removed), wrapped in @layer components. */\n`;
fs.writeFileSync(new URL('../src/styles/components.css', import.meta.url), header + '@layer components {\n' + css + '\n}\n');
console.log(`ported: ${renamed} token references renamed, ${removed} :root blocks removed, ${css.split('\n').length} lines`);
